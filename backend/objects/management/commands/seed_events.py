class Command(BaseCommand):
    help = 'Створює 50 тимчасових подій з реалістичними описами'

    def add_arguments(self, parser):
        parser.add_argument(
            '--count',
            type=int,
            default=50,
            help='Кількість подій для створення (за замовчуванням 50)',
        )
        parser.add_argument(
            '--author',
            type=str,
            default='testuser',
            help='username автора подій (за замовчуванням testuser)',
        )

    def handle(self, *args, **options):
        count = options['count']
        author_username = options['author']

        author = User.objects.filter(username=author_username).first()
        if author is None:
            author = User.objects.filter(is_superuser=True).first()
        if author is None:
            self.stderr.write(self.style.ERROR(
                f'Не знайдено користувача "{author_username}" і немає суперюзера. '
                f'Спочатку виконайте seed_data або створіть користувача.'
            ))
            return

        event_tags = {t.slug: t for t in Tag.objects.filter(tag_type='event')}
        if not event_tags:
            self.stderr.write(self.style.ERROR(
                'Немає тегів типу "event". Запустіть seed_data, щоб створити теги.'
            ))
            return

        now = timezone.now()
        pool = list(EVENTS_POOL)
        random.shuffle(pool)

        created = 0
        for i in range(count):
            template = pool[i % len(pool)]
            title, description, tag_slug, duration_days = template

            # Дублікати — додаємо рік (напр. " 2026") до назви, щоб уникнути плутанини
            if i >= len(EVENTS_POOL):
                title = f'{title} (вип. {i // len(EVENTS_POOL) + 1})'

            city, city_lat, city_lng = random.choice(CITIES)
            # Невеликий зсув у межах міста, щоб точки не лягали одна на одну
            lat = round(city_lat + random.uniform(-0.04, 0.04), 6)
            lng = round(city_lng + random.uniform(-0.04, 0.04), 6)

            # Початок події — від +1 до +180 днів від сьогодні
            start_offset = random.randint(1, 180)
            start = now + timedelta(days=start_offset, hours=random.choice([10, 11, 12, 14, 16, 18, 19]))
            end = start + timedelta(days=duration_days)

            full_description = f'{description}\n\nМісце проведення: {city}.'

            obj = CulturalObject.objects.create(
                title=title,
                description=full_description,
                latitude=Decimal(str(lat)),
                longitude=Decimal(str(lng)),
                author=author,
                status=CulturalObject.Status.APPROVED,
                object_type=CulturalObject.ObjectType.EVENT,
                event_start_date=start,
                event_end_date=end,
            )

            tag = event_tags.get(tag_slug)
            if tag:
                obj.tags.add(tag)
            # Іноді додаємо другий випадковий event-тег для різноманітності
            if random.random() < 0.3:
                extras = [t for slug, t in event_tags.items() if slug != tag_slug]
                if extras:
                    obj.tags.add(random.choice(extras))

            created += 1
            if created % 10 == 0:
                self.stdout.write(f'  ... створено {created}/{count}')

        self.stdout.write(self.style.SUCCESS(
            f'Створено {created} тимчасових подій (автор: {author.username})'
        ))