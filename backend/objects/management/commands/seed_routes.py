class Command(BaseCommand):
    help = 'Створює реальні культурні об\'єкти та 20 туристичних маршрутів для користувача osavenko'

    def handle(self, *args, **options):
        try:
            user = User.objects.get(username='osavenko')
        except User.DoesNotExist:
            self.stderr.write(self.style.ERROR(
                'Користувач osavenko не знайдений. '
                'Спочатку створіть його через реєстрацію або createsuperuser.'
            ))
            return

        tags_map = {tag.slug: tag for tag in Tag.objects.all()}
        missing_tags = {
            slug
            for obj in OBJECTS.values()
            for slug in obj['tags']
            if slug not in tags_map
        }
        if missing_tags:
            self.stderr.write(self.style.ERROR(
                f'Відсутні теги: {", ".join(sorted(missing_tags))}. '
                'Спочатку запустіть seed_data для створення тегів.'
            ))
            return

        # Step 1: ensure objects exist.
        self.stdout.write('Крок 1/2: Створення культурних об\'єктів...')
        obj_map = {}
        created_objects = 0
        for key, data in OBJECTS.items():
            obj, created = CulturalObject.objects.get_or_create(
                title=data['title'],
                author=user,
                defaults={
                    'description': data['description'],
                    'latitude': Decimal(data['lat']),
                    'longitude': Decimal(data['lng']),
                    'status': CulturalObject.Status.APPROVED,
                    'wikipedia_url': data.get('wikipedia_url', ''),
                },
            )
            obj_map[key] = obj
            if created:
                obj.tags.set([tags_map[slug] for slug in data['tags']])
                created_objects += 1
                self.stdout.write(f'  + {data["title"]}')
            else:
                self.stdout.write(f'  = вже існує: {data["title"]}')
        self.stdout.write(self.style.SUCCESS(f'Об\'єктів створено: {created_objects}'))

        # Step 2: build routes with ordered stops.
        self.stdout.write('\nКрок 2/2: Створення маршрутів...')
        created_routes = 0
        for route_data in ROUTES:
            if Route.objects.filter(title=route_data['title'], author=user).exists():
                self.stdout.write(f'  Пропущено (вже існує): {route_data["title"]}')
                continue

            route = Route.objects.create(
                title=route_data['title'],
                description=route_data['description'],
                author=user,
                visibility=Route.Visibility.PUBLIC,
                status=Route.Status.APPROVED,
                is_featured=True,
                estimated_duration_minutes=route_data.get('duration'),
                original_language='uk',
            )
            route.tags.set([tags_map[slug] for slug in route_data.get('tags', []) if slug in tags_map])

            for order, (obj_key, note) in enumerate(route_data['stops'], start=1):
                RouteStop.objects.create(
                    route=route,
                    cultural_object=obj_map[obj_key],
                    order=order,
                    note=note,
                )

            created_routes += 1
            self.stdout.write(f'  + {route_data["title"]} ({len(route_data["stops"])} зупинок)')

        self.stdout.write(self.style.SUCCESS(
            f'\nСтворено {created_routes} маршрутів для osavenko'
        ))
